
CREATE TABLE purchase_orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    order_number VARCHAR(50) NOT NULL UNIQUE,

    supplier_id BIGINT NOT NULL,
    warehouse_id BIGINT NOT NULL,

    status VARCHAR(20) NOT NULL DEFAULT 'DRAFT',

    order_date DATE NOT NULL DEFAULT CURRENT_DATE,
    expected_delivery_date DATE,
    received_at TIMESTAMP,

    total_amount NUMERIC(14, 2) NOT NULL DEFAULT 0,

    notes VARCHAR(500),

    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_purchase_order_supplier
        FOREIGN KEY (supplier_id) REFERENCES suppliers(id),

    CONSTRAINT fk_purchase_order_warehouse
        FOREIGN KEY (warehouse_id) REFERENCES warehouses(id),

    CONSTRAINT chk_purchase_order_status
        CHECK (status IN ('DRAFT', 'ORDERED', 'RECEIVED', 'CANCELLED')),

    CONSTRAINT chk_purchase_order_total
        CHECK (total_amount >= 0)
);

CREATE TABLE purchase_order_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    purchase_order_id BIGINT NOT NULL,
    product_id BIGINT NOT NULL,

    quantity NUMERIC(14, 3) NOT NULL,
    unit_price NUMERIC(12, 2) NOT NULL,
    line_total NUMERIC(14, 2) NOT NULL,

    CONSTRAINT fk_purchase_order_item_order
        FOREIGN KEY (purchase_order_id)
        REFERENCES purchase_orders(id),

    CONSTRAINT fk_purchase_order_item_product
        FOREIGN KEY (product_id)
        REFERENCES products(id),

    CONSTRAINT chk_purchase_order_item_quantity
        CHECK (quantity > 0),

    CONSTRAINT chk_purchase_order_item_price
        CHECK (unit_price >= 0),

    CONSTRAINT chk_purchase_order_item_total
        CHECK (line_total >= 0)
);

CREATE INDEX idx_purchase_orders_supplier
    ON purchase_orders(supplier_id);

CREATE INDEX idx_purchase_orders_warehouse
    ON purchase_orders(warehouse_id);

CREATE INDEX idx_purchase_orders_status
    ON purchase_orders(status);

CREATE INDEX idx_purchase_order_items_order
    ON purchase_order_items(purchase_order_id);
